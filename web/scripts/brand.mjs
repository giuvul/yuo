// Builds the brand files from the master SVGs in docs/assets/logo/master/.
//
//   node scripts/brand.mjs          write src/components/logoPaths.ts, public/*.svg, docs/assets/logo/*.svg
//   node scripts/brand.mjs --png    also render the PNG icons and favicon.ico (needs Playwright's chromium)
//
// The masters carry hairline strokes; only the path geometry and the approved colours are kept. The geometry is never edited here: icons only place and scale the symbol.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const WEB = join(dirname(fileURLToPath(import.meta.url)), "..");
const BRAND = join(WEB, "..", "docs", "assets", "logo", "master");
const ASSETS = join(WEB, "..", "docs", "assets", "logo");
const PUBLIC = join(WEB, "public");

const FOREST = "#1E3B2F";
const MOSS = "#4F7A5A";
const MIST = "#EEF3EC";

function paths(name) {
  const svg = readFileSync(join(BRAND, name), "utf8").replace(/<metadata[\s\S]*?<\/metadata>/, "");
  const viewBox = /viewBox="([^"]+)"/.exec(svg)[1];
  const list = [...svg.matchAll(/<path\b[^>]*?\sd="([^"]+)"[^>]*?fill="([^"]+)"|<path\b[^>]*?fill="([^"]+)"[^>]*?\sd="([^"]+)"/g)].map(
    (m) => ({ d: m[1] ?? m[4], fill: (m[2] ?? m[3]).toUpperCase() }),
  );
  return { viewBox, list };
}

function bbox(ds) {
  let x0 = Infinity, y0 = Infinity, x1 = -Infinity, y1 = -Infinity;
  for (const d of ds) {
    const n = d.match(/-?\d+\.?\d*/g).map(Number);
    for (let i = 0; i < n.length; i += 2) {
      x0 = Math.min(x0, n[i]); x1 = Math.max(x1, n[i]);
      y0 = Math.min(y0, n[i + 1]); y1 = Math.max(y1, n[i + 1]);
    }
  }
  return { x: x0, y: y0, w: x1 - x0, h: y1 - y0 };
}

// the primary logo: Forest letters and left leaf, Moss right leaf (the only Moss path)
const logo = paths("yuo-logo-primary.svg");
const symbol = paths("yuo-symbol-brand.svg");
const split = ({ list }) => ({
  body: list.filter((p) => p.fill === FOREST).map((p) => p.d),
  leaf: list.filter((p) => p.fill === MOSS).map((p) => p.d),
});
const L = split(logo);
const S = split(symbol);
if (L.leaf.length !== 1 || S.leaf.length !== 1 || !L.body.length || !S.body.length) {
  throw new Error("brand: the master SVGs do not have the expected Forest/Moss paths");
}
const pad = (b, p) => `${(b.x - p).toFixed(0)} ${(b.y - p).toFixed(0)} ${(b.w + 2 * p).toFixed(0)} ${(b.h + 2 * p).toFixed(0)}`;
const logoBox = bbox([...L.body, ...L.leaf]);
const symbolBox = bbox([...S.body, ...S.leaf]);

writeFileSync(
  join(WEB, "src", "components", "logoPaths.ts"),
  `// Generated by scripts/brand.mjs from docs/assets/logo/master/yuo-logo-primary.svg and yuo-symbol-brand.svg. Do not edit:
// the geometry is the approved logo (A4, "Bold, Large Y"). \`body\` is everything in the main colour, \`leaf\` the
// right leaf (Moss in the primary logo).
export const LOGO = {
  viewBox: "${pad(logoBox, 4)}",
  width: ${(logoBox.w + 8).toFixed(0)},
  height: ${(logoBox.h + 8).toFixed(0)},
  body: ${JSON.stringify(L.body)},
  leaf: ${JSON.stringify(L.leaf[0])},
};

export const SYMBOL = {
  viewBox: "${pad(symbolBox, 4)}",
  width: ${(symbolBox.w + 8).toFixed(0)},
  height: ${(symbolBox.h + 8).toFixed(0)},
  body: ${JSON.stringify(S.body)},
  leaf: ${JSON.stringify(S.leaf[0])},
};
`,
);

const svg = (viewBox, inner, title) =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}"${title ? ` role="img"><title>${title}</title>` : ">"}${inner}</svg>\n`;
const art = (p, main, leaf) => `${p.body.map((d) => `<path fill="${main}" fill-rule="evenodd" d="${d}"/>`).join("")}<path fill="${leaf}" d="${p.leaf[0]}"/>`;

// clean masters for the README and docs
mkdirSync(ASSETS, { recursive: true });
for (const [name, main, leaf] of [["primary", FOREST, MOSS], ["forest", FOREST, FOREST], ["mist", MIST, MIST]]) {
  writeFileSync(join(ASSETS, `yuo-logo-${name}.svg`), svg(pad(logoBox, 4), art(L, main, leaf), "yuo"));
  writeFileSync(join(ASSETS, `yuo-symbol-${name}.svg`), svg(pad(symbolBox, 4), art(S, main, leaf), "yuo"));
}

/** The app icon (section 4): the Mist sprout with a Moss right leaf on Forest, optically centred. */
function icon({ radius, share }) {
  const size = 512;
  const k = (size * share) / symbolBox.w;
  const tx = (size - symbolBox.w * k) / 2 - symbolBox.x * k;
  const ty = (size - symbolBox.h * k) / 2 - symbolBox.y * k;
  return svg(
    `0 0 ${size} ${size}`,
    `<rect width="${size}" height="${size}" rx="${(size * radius).toFixed(1)}" fill="${FOREST}"/>` +
      `<g transform="translate(${tx.toFixed(2)} ${ty.toFixed(2)}) scale(${k.toFixed(4)})">${art(S, MIST, MOSS)}</g>`,
  );
}
const ICONS = {
  "icon.svg": icon({ radius: 0.22, share: 0.6 }),
  // maskable: full bleed, the symbol inside the safe zone (the inner 80% circle)
  "icon-maskable.svg": icon({ radius: 0, share: 0.44 }),
  // small sizes: a slightly larger symbol stays legible at 16 px
  "favicon.svg": icon({ radius: 0.22, share: 0.65 }),
};
for (const [name, body] of Object.entries(ICONS)) writeFileSync(join(PUBLIC, name), body);
console.log("brand: wrote logoPaths.ts, public icons and docs/assets/logo");

if (process.argv.includes("--png")) {
  const { chromium } = await import("@playwright/test");
  const browser = await chromium.launch();
  const page = await browser.newPage();
  const png = async (source, size) => {
    await page.setViewportSize({ width: size, height: size });
    await page.setContent(`<style>html,body{margin:0;background:transparent}svg{display:block;width:${size}px;height:${size}px}</style>${source}`);
    return page.screenshot({ omitBackground: true });
  };
  const out = {
    "icon-192.png": [ICONS["icon.svg"], 192],
    "icon-512.png": [ICONS["icon.svg"], 512],
    "icon-256.png": [ICONS["icon.svg"], 256],
    "icon-maskable-512.png": [ICONS["icon-maskable.svg"], 512],
    // iOS rounds the corners itself: full bleed
    "apple-touch-icon.png": [icon({ radius: 0, share: 0.56 }), 180],
    "favicon-16.png": [ICONS["favicon.svg"], 16],
    "favicon-32.png": [ICONS["favicon.svg"], 32],
    "favicon-48.png": [ICONS["favicon.svg"], 48],
  };
  const made = {};
  for (const [name, [source, size]] of Object.entries(out)) {
    made[name] = await png(source, size);
    writeFileSync(join(PUBLIC, name), made[name]);
  }
  await browser.close();
  // favicon.ico: a container of the 16, 32 and 48 px PNGs
  const entries = [16, 32, 48].map((s) => ({ s, data: made[`favicon-${s}.png`] }));
  const head = Buffer.alloc(6 + 16 * entries.length);
  head.writeUInt16LE(1, 2);
  head.writeUInt16LE(entries.length, 4);
  let offset = head.length;
  entries.forEach(({ s, data }, i) => {
    const at = 6 + 16 * i;
    head.writeUInt8(s, at);
    head.writeUInt8(s, at + 1);
    head.writeUInt16LE(1, at + 4);
    head.writeUInt16LE(32, at + 6);
    head.writeUInt32LE(data.length, at + 8);
    head.writeUInt32LE(offset, at + 12);
    offset += data.length;
  });
  writeFileSync(join(PUBLIC, "favicon.ico"), Buffer.concat([head, ...entries.map((e) => e.data)]));
  console.log("brand: rendered PNG icons and favicon.ico");
}
